    /// C1/C4 under REAL concurrent writers: the property the conformance suite's
    /// `SINGLE_WRITER_CAVEAT` says it cannot prove. N threads × M admits against ONE scope
    /// with a hard cap — different pool connections, serialized only by the scope's advisory
    /// lock — must never let held + spent exceed the cap, and must deny the overflow.
    #[test]
    #[ignore = "requires SANDHI_TEST_PG_DSN"]
    fn concurrent_threads_on_one_scope_never_oversubscribe_the_cap() {
        let schema = test_schema("threads");
        let ledger = Arc::new(pg_ledger("threads"));
        const CAP: u64 = 1000;
        const CEILING: u64 = 25;
        const THREADS: usize = 8;
        const ATTEMPTS: usize = 25;
        ledger
            .set_limit_durable("contended", Some(CAP), Window::Total, Policy::Block)
            .unwrap();

        let admitted = Arc::new(AtomicU64::new(0));
        let denied = Arc::new(AtomicU64::new(0));
        let mut handles = Vec::new();
        for _ in 0..THREADS {
            let (ledger, admitted, denied) = (
                Arc::clone(&ledger),
                Arc::clone(&admitted),
                Arc::clone(&denied),
            );
            handles.push(std::thread::spawn(move || {
                for _ in 0..ATTEMPTS {
                    match ledger.reserve_durable(
                        "contended",
                        CEILING,
                        OffsetDateTime::now_utc(),
                        ttl(),
                    ) {
                        Ok(ReserveOutcome::Admitted(reservation)) => {
                            admitted.fetch_add(1, Ordering::Relaxed);
                            // Settle immediately: spend accrues, headroom does not return.
                            ledger.settle_durable(reservation.id, CEILING).unwrap();
                        }
                        Ok(ReserveOutcome::Denied(_)) => {
                            denied.fetch_add(1, Ordering::Relaxed);
                        }
                        Err(error) => panic!("storage error must not happen in the test: {error}"),
                    }
                    // The invariant at every step, on every thread.
                    let spent = ledger.spent_durable("contended").unwrap();
                    let reserved = ledger.reserved_durable("contended").unwrap();
                    assert!(
                        spent + reserved <= CAP,
                        "cap breached: spent({spent}) + reserved({reserved}) > {CAP}"
                    );
                }
            }));
        }
        for handle in handles {
            handle.join().expect("thread must not panic");
        }

        let total_admitted = admitted.load(Ordering::Relaxed);
        let total_denied = denied.load(Ordering::Relaxed);
        assert_eq!(
            THREADS * ATTEMPTS,
            (total_admitted + total_denied) as usize,
            "every attempt must be exactly admitted or denied"
        );
        assert!(
            total_denied > 0,
            "8x25 attempts of 25 tokens against a 1000 cap must deny the overflow"
        );
        assert_eq!(
            total_admitted * CEILING,
            ledger.spent_durable("contended").unwrap(),
            "each admission settled its full ceiling"
        );
        assert_eq!(ledger.reserved_durable("contended").unwrap(), 0);
        drop_schema_best_effort(&schema);
    }

