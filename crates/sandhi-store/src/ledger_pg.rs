    #[test]
    #[ignore = "requires SANDHI_TEST_PG_DSN"]
    fn hierarchical_windows_roll_independently_and_capacity_returns_with_time() {
        let schema = test_schema("hierarchy");
        let ledger = pg_ledger("hierarchy");
        ledger
            .set_limits_durable(
                "group:h",
                &[
                    (Some(100), Window::Hourly, Policy::Block),
                    (Some(500), Window::Daily, Policy::Block),
                    (Some(700), Window::Weekly, Policy::Block),
                    (Some(1200), Window::Monthly, Policy::Block),
                ],
                true,
            )
            .unwrap();
        let now = OffsetDateTime::now_utc();
        for (seconds_ago, actual) in [
            (3_600 * 2, 399),       // hourly out; daily/weekly/monthly in
            (86_400 + 1, 20),       // daily out; weekly/monthly in
            (86_400 * 7 + 1, 400),  // weekly out; monthly in
            (86_400 * 30 + 1, 500), // monthly out
        ] {
            ledger.insert_settled("group:h", actual, now.unix_timestamp() - seconds_ago);
        }

        // Rolling sums at this instant are hourly 0, daily 399, weekly 419, monthly 890.
        let reservation = match ledger.reserve_durable("group:h", 100, now, ttl()).unwrap() {
            ReserveOutcome::Admitted(reservation) => reservation,
            ReserveOutcome::Denied(denied) => panic!("expected admission: {denied:?}"),
        };
        ledger.settle_durable(reservation.id, 100).unwrap();
        assert!(
            matches!(
                ledger.reserve_durable("group:h", 1, now, ttl()).unwrap(),
                ReserveOutcome::Denied(_)
            ),
            "the current hourly window is full"
        );

        // One second after the hourly boundary the old 100-token settlement is outside
        // hourly, but remains in daily. Hourly capacity returns without a calendar-day reset.
        let later = now + TimeDuration::seconds(3_601);
        assert!(matches!(
            ledger.reserve_durable("group:h", 1, later, ttl()).unwrap(),
            ReserveOutcome::Admitted(_)
        ));
        let daily_start = window_start_ts(later, Window::Daily);
        let daily_spent: i64 = ledger.block(async {
            sqlx::query_scalar(
                "SELECT COALESCE(SUM(actual), 0)::bigint FROM budget_reservation \
                 WHERE scope = 'group:h' AND settled = 1 \
                   AND COALESCE(settled_at, 0) > $1",
            )
            .bind(daily_start)
            .fetch_one(&ledger.pool)
            .await
            .expect("daily spend")
        });
        let reserved = ledger.reserved_durable("group:h").unwrap();
        assert_eq!((daily_spent, reserved), (499, 1));
        assert!(
            matches!(
                ledger
                    .reserve_durable("group:h", 1, later, ttl())
                    .unwrap(),
                ReserveOutcome::Denied(denied) if denied.limit == 500
            ),
            "the daily hierarchy remains binding while hourly capacity has rolled"
        );
        drop_schema_best_effort(&schema);
    }

