/// Advisory key for the retained-intent `COUNT(*)` in `reserve_intent` (PR-B). Scope keys are
/// always non-negative (masked to `i64::MAX`), so any negative key is dedicated: the
/// retained-limit admission check can take this lock without ever colliding with a scope.
pub const RESERVED_COUNT_ADVISORY_KEY: i64 = -1;

/// The advisory-lock identity of a scope: FNV-1a 64-bit of the scope bytes (the same stable
/// function the sharded ledger routes by) masked into a non-negative `i64`. Stable forever by
/// construction of [`crate::fnv1a`] — an operator must never see a cap move because a hash
/// algorithm changed under it.
pub fn scope_advisory_key(scope: &str) -> i64 {
    (fnv1a(scope.as_bytes()) & (i64::MAX as u64)) as i64
}

/// Advisory keys for a transaction touching several scopes, ASCENDING. Every multi-scope
/// transaction (a paired admit, PR-B's `reserve_intent`) MUST take its locks in this order:
/// a global lock order is what makes the paired admit deadlock-free under concurrent
/// opposite-order pairing.
pub fn advisory_keys_ascending(scopes: &[&str]) -> Vec<i64> {
    let mut keys: Vec<i64> = scopes
        .iter()
        .map(|scope| scope_advisory_key(scope))
        .collect();
    keys.sort_unstable();
    keys.dedup();
    keys
}

/// Idempotent schema init, mirroring the SQLite ledger's DDL column-for-column. Storage types
/// map TEXT→text, INTEGER→bigint; `id` becomes an identity column (migration inserts explicit
/// ids then re-`setval`s — [`PostgresLedger::insert_migrated_reservation`]); the covering
/// index keeps its name and column order. No CHECK constraints to translate: the SQLite
/// ledger-core tables carry none, and `settled` deliberately stays a plain 0/1 bigint rather
/// than a boolean (parity with the shared SUM fragments).
const DDL: &[&str] = &[
    // Born upgraded: one budget per (scope, window) — the two-column primary key the SQLite
    // ledger migrates to. No legacy single-window upgrade path exists on PG.
    "CREATE TABLE IF NOT EXISTS budget_limit (
        scope        text NOT NULL,
        limit_tokens bigint,
        \"window\"       text NOT NULL DEFAULT 'total',
        policy       text NOT NULL DEFAULT 'block',
        PRIMARY KEY (scope, \"window\")
    )",
    "CREATE TABLE IF NOT EXISTS budget_reservation (
        id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        scope      text   NOT NULL,
        ceiling    bigint NOT NULL,
        actual     bigint NOT NULL DEFAULT 0,
        settled    bigint NOT NULL DEFAULT 0,
        settled_at bigint,
        expires_at bigint NOT NULL
    )",
    // Same columns, same name, same purpose as the SQLite covering index (design audit A5):
    // the spent/reserved SUMs must stay index-only scans as the scope's settled history grows.
    "CREATE INDEX IF NOT EXISTS idx_reservation_scope_covering
        ON budget_reservation (scope, settled, settled_at, actual, ceiling, expires_at)",
    // TD-0021 P4 (D2): dedup state lives WITH the ledger. Key is the full
    // (virtual_key_id, idempotency_key) pair (R1 — no body hash); the row carries the settled
    // reservation so a repeat can reuse the original settlement.
    "CREATE TABLE IF NOT EXISTS idempotency_dedup (
        vkey        text   NOT NULL,
        idem_key    text   NOT NULL,
        reservation bigint NOT NULL,
        actual      bigint NOT NULL,
        seen_at     bigint NOT NULL,
        expires_at  bigint NOT NULL,
        PRIMARY KEY (vkey, idem_key)
    )",
];

/// The per-window ordering fragment (shortest configured window first, `total` last) — the
/// PG dialect of [`crate::ledger::SqliteLedger::window_order_sql`]. `window` is a reserved
/// word in Postgres, so the column is always quoted.
const WINDOW_ORDER_SQL: &str = "CASE \"window\" WHEN 'hourly' THEN 0 WHEN 'daily' THEN 1 \
     WHEN 'weekly' THEN 2 WHEN 'monthly' THEN 3 ELSE 4 END, \"window\"";

/// The guarded settle: `settled = 0` makes a replayed settle update zero rows (C2), and
/// `EXTRACT(EPOCH FROM now())::bigint` stamps the transaction clock — the PG dialect of
/// SQLite's `strftime('%s','now')`. Pinned by a dialect test.
const SETTLE_SQL: &str = "UPDATE budget_reservation \
     SET actual = $2, settled = 1, settled_at = EXTRACT(EPOCH FROM now())::bigint \
     WHERE id = $1 AND settled = 0";

/// A durable enforcement ledger backed by a Postgres pool. All methods take `&self` — the
/// pool is the shared resource, so a future `ProxyLedger` arm stays structurally identical to
/// the sharded arm (which also hands out `&self` behind per-shard mutexes). Single-writer
/// posture: one process owns the ledger; cross-connection admission safety comes from the
/// per-scope advisory locks, not from multiple writers being supported.
pub struct PostgresLedger {
    pool: PgPool,
    /// The runtime that owns the pool's background tasks. All statements are `block_on`'d
    /// through this handle from ordinary blocking threads. Never call ledger methods from an
    /// async executor task.
    rt: tokio::runtime::Handle,
}

impl PostgresLedger {
    /// Connect and initialize the schema (idempotent `CREATE IF NOT EXISTS`). The pool is
    /// small on purpose: one admission lane per scope plus a few readers is all a ledger
    /// serves, and every admit serializes on its scope's advisory lock anyway.
    ///
    /// Must be called on a `tokio` runtime; that runtime's handle is retained for every later
    /// blocking statement.
    pub async fn connect(dsn: &str) -> Result<Self, LedgerStoreError> {
        let options: PgConnectOptions = dsn
            .parse()
            .map_err(|e| LedgerStoreError::Backend(format!("invalid ledger DSN: {e}")))?;
        Self::connect_with(options).await
    }

    /// Like [`Self::connect`] from pre-parsed options (the test suite points `search_path`
    /// at a per-test schema for isolation against shared instances).
    async fn connect_with(options: PgConnectOptions) -> Result<Self, LedgerStoreError> {
        let pool = PgPoolOptions::new()
            .max_connections(8)
            .acquire_timeout(Duration::from_secs(5))
            .connect_with(options)
            .await?;
        for statement in DDL {
            sqlx::query(statement).execute(&pool).await?;
        }
        Ok(Self {
            pool,
            rt: tokio::runtime::Handle::current(),
        })
    }

    /// Run one statement batch on the retained runtime handle. Callers must be blocking
    /// threads (see the module docs) — `Handle::block_on` panics inside an async task by
    /// design, which keeps this mis-use loud instead of silently serializing a worker.
    fn block<T>(&self, fut: impl Future<Output = T>) -> T {
        self.rt.block_on(fut)
    }

    /// Postgres is always a durable, restart-surviving backend — there is no volatile mode.
    /// The evidence subsystem's file-backed gate (PR-B) admits this ledger by construction;
    /// exposed until then so operators/probes can assert the same fact.
    pub fn is_file_backed(&self) -> bool {
        true
    }

    /// Set (or clear the cap with `limit = None`) a scope's durable budget: cap + window +
    /// policy. Clears the scope's whole hierarchy first, exactly like the SQLite arm.
    pub fn set_limit_durable(
        &self,
        scope: &str,
        limit: Option<u64>,
        window: Window,
        policy: Policy,
    ) -> Result<(), LedgerStoreError> {
        self.block(self.set_limit_async(scope, limit, window, policy))
    }

    async fn set_limit_async(
        &self,
        scope: &str,
        limit: Option<u64>,
        window: Window,
        policy: Policy,
    ) -> Result<(), LedgerStoreError> {
        // PG bigint is signed. Never wrap a requested cap into a negative value.
        let limit = checked_i64(limit)?;
        let mut tx = self.pool.begin().await?;
        sqlx::query("DELETE FROM budget_limit WHERE scope = $1")
            .bind(scope)
            .execute(&mut *tx)
            .await?;
        if let Some(limit) = limit {
            sqlx::query(
                "INSERT INTO budget_limit (scope, \"window\", limit_tokens, policy) \
                 VALUES ($1, $2, $3, $4)",
            )
            .bind(scope)
            .bind(window.as_str())
            .bind(limit)
            .bind(policy.as_str())
            .execute(&mut *tx)
            .await?;
        }
        tx.commit().await?;
        Ok(())
    }

    /// Atomically install every `(window, limit, policy)` row for one scope. With `replace`,
    /// the scope's omitted rows are removed first; otherwise this is an additive upsert. A
    /// later storage failure cannot publish a partial result (one transaction).
    pub fn set_limits_durable(
        &self,
        scope: &str,
        limits: &[(Option<u64>, Window, Policy)],
        replace: bool,
    ) -> Result<(), LedgerStoreError> {
        self.block(self.set_limits_async(scope, limits, replace))
    }

    async fn set_limits_async(
        &self,
        scope: &str,
        limits: &[(Option<u64>, Window, Policy)],
        replace: bool,
    ) -> Result<(), LedgerStoreError> {
        if limits.is_empty() {
            return Err(LedgerStoreError::Backend(
                "budget hierarchy must not be empty".into(),
            ));
        }
        let mut tx = self.pool.begin().await?;
        if replace {
            sqlx::query("DELETE FROM budget_limit WHERE scope = $1")
                .bind(scope)
                .execute(&mut *tx)
                .await?;
        }
        for (limit, window, policy) in limits {
            let limit = checked_i64(*limit)?;
            sqlx::query(
                "INSERT INTO budget_limit (scope, \"window\", limit_tokens, policy) \
                 VALUES ($1, $2, $3, $4) \
                 ON CONFLICT (scope, \"window\") DO UPDATE SET \
                     limit_tokens = excluded.limit_tokens, \
                     policy = excluded.policy",
            )
            .bind(scope)
            .bind(window.as_str())
            .bind(limit)
            .bind(policy.as_str())
            .execute(&mut *tx)
            .await?;
        }
        tx.commit().await?;
        Ok(())
    }

    /// The configured window for a scope (defaults to `Total` when unset).
    pub fn window_of_durable(&self, scope: &str) -> Result<Window, LedgerStoreError> {
        self.block(self.window_of_async(scope))
    }

    async fn window_of_async(&self, scope: &str) -> Result<Window, LedgerStoreError> {
        let window: Option<String> = sqlx::query_scalar(&format!(
            "SELECT \"window\" FROM budget_limit WHERE scope = $1 ORDER BY {WINDOW_ORDER_SQL} LIMIT 1",
        ))
        .bind(scope)
        .fetch_optional(&self.pool)
        .await?;
        Ok(window.map(|s| Window::parse(&s)).unwrap_or_default())
    }

    /// The configured policy for a scope (defaults to `Block` when unset).
    pub fn policy_of_durable(&self, scope: &str) -> Result<Policy, LedgerStoreError> {
        self.block(self.policy_of_async(scope))
    }

    async fn policy_of_async(&self, scope: &str) -> Result<Policy, LedgerStoreError> {
        let policy: Option<String> = sqlx::query_scalar(
            "SELECT policy FROM budget_limit WHERE scope = $1 AND policy = 'block' LIMIT 1",
        )
        .bind(scope)
        .fetch_optional(&self.pool)
        .await?;
        Ok(policy.map(|s| Policy::parse(&s)).unwrap_or_default())
    }

    /// Atomically admit a call by holding `ceiling` tokens as a lease expiring at `now + ttl`,
    /// or deny it if the ceiling would breach a set cap. Reclaims this scope's expired leases
    /// first so a legacy crashed reservation never blocks admission (ADR-0005 D2).
    ///
    /// The C3 admit: one READ COMMITTED transaction under the scope's transactional advisory
    /// lock — reclaim-then-read-then-check-then-insert — so two connections cannot both admit
    /// against a stale read. On a denial the whole transaction rolls back: the opportunistic
    /// reclaim inside it is discarded exactly as on SQLite, and the next admit re-reclaims.
    pub fn reserve_durable(
        &self,
        scope: &str,
        ceiling: u64,
        now: OffsetDateTime,
        ttl: TimeDuration,
    ) -> Result<ReserveOutcome, LedgerStoreError> {
        self.block(self.reserve_async(scope, ceiling, now, ttl))
    }

    async fn reserve_async(
        &self,
        scope: &str,
        ceiling: u64,
        now: OffsetDateTime,
        ttl: TimeDuration,
    ) -> Result<ReserveOutcome, LedgerStoreError> {
        let checked_ceiling = checked_i64(Some(ceiling))?.expect("Some(ceiling)");
        let now_ts = now.unix_timestamp();
        let expires_at = (now + ttl).unix_timestamp();
        let mut tx = self.pool.begin().await?;
        // Serialize this scope's whole read-check-write sequence. READ COMMITTED alone would
        // still let two concurrent admits read the same SUM; the lock is the write lock.
        sqlx::query("SELECT pg_advisory_xact_lock($1)")
            .bind(scope_advisory_key(scope))
            .execute(&mut *tx)
            .await?;
        // Opportunistic reclaim: drop this scope's unsettled, expired leases before measuring.
        // PR-B adds the NOT-EXISTS guards for the evidence tables (intent / back leg / fence);
        // on a PR-A ledger nothing can be tracked, so the unguarded delete is exact.
        sqlx::query(
            "DELETE FROM budget_reservation \
             WHERE scope = $1 AND settled = 0 AND expires_at <= $2",
        )
        .bind(scope)
        .bind(now_ts)
        .execute(&mut *tx)
        .await?;

        let budgets: Vec<(Option<i64>, String, String)> = sqlx::query_as(&format!(
            "SELECT limit_tokens, \"window\", policy FROM budget_limit \
             WHERE scope = $1 ORDER BY {WINDOW_ORDER_SQL}",
        ))
        .bind(scope)
        .fetch_all(&mut *tx)
        .await?;

        if !budgets.is_empty() {
            let reserved: i64 = sqlx::query_scalar(
                "SELECT COALESCE(SUM(ceiling), 0)::bigint FROM budget_reservation \
                 WHERE scope = $1 AND settled = 0",
            )
            .bind(scope)
            .fetch_one(&mut *tx)
            .await?;
            for (limit, window, policy) in budgets {
                let Some(limit) = limit else { continue };
                let start = window_start_ts(now, Window::parse(&window));
                let spent: i64 = sqlx::query_scalar(
                    "SELECT COALESCE(SUM(actual), 0)::bigint FROM budget_reservation \
                     WHERE scope = $1 AND settled = 1 AND COALESCE(settled_at, 0) > $2",
                )
                .bind(scope)
                .bind(start)
                .fetch_one(&mut *tx)
                .await?;
                // `Warn` is a soft cap: it never denies admission. Every hard window is
                // checked independently against its own trailing consumption and shared
                // in-flight holds.
                if Policy::parse(&policy) == Policy::Block
                    && i128::from(spent) + i128::from(reserved) + i128::from(ceiling)
                        > i128::from(limit)
                {
                    // Roll back everything — including the opportunistic reclaim — nothing
                    // reserved, exactly like the SQLite arm's transaction drop.
                    tx.rollback().await?;
                    return Ok(ReserveOutcome::Denied(Denied {
                        scope: scope.to_string(),
                        limit: limit.max(0) as u64,
                        spent: spent.max(0) as u64,
                        reserved: reserved.max(0) as u64,
                        requested_ceiling: ceiling,
                    }));
                }
            }
        }

        // RETURNING id replaces SQLite's last_insert_rowid.
        let id: i64 = sqlx::query_scalar(
            "INSERT INTO budget_reservation (scope, ceiling, expires_at) \
             VALUES ($1, $2, $3) RETURNING id",
        )
        .bind(scope)
        .bind(checked_ceiling)
        .bind(expires_at)
        .fetch_one(&mut *tx)
        .await?;
        tx.commit().await?;
        Ok(ReserveOutcome::Admitted(Reservation {
            id: id as u64,
            scope: scope.to_string(),
            ceiling,
            expires_at: now + ttl,
        }))
    }

    /// Idempotently settle a reservation to its actual billable usage. Guarded by
    /// `settled = 0`, so a retried or replayed settle updates zero rows and changes nothing
    /// (ADR-0005 D2/C2). The guard makes this a CAS-shaped single statement, safe under READ
    /// COMMITTED without the scope lock.
    ///
    /// PR-B adds the tracked-reservation refusal ([`LedgerStoreError::TrackedSettlementRequired`])
    /// once the evidence tables exist; on a PR-A ledger no reservation can be tracked.
    pub fn settle_durable(&self, reservation_id: u64, actual: u64) -> Result<(), LedgerStoreError> {
        self.block(self.settle_async(reservation_id, actual))
    }

    async fn settle_async(&self, reservation_id: u64, actual: u64) -> Result<(), LedgerStoreError> {
        sqlx::query(SETTLE_SQL)
            .bind(reservation_id as i64)
            .bind(actual as i64)
            .execute(&self.pool)
            .await?;
        Ok(())
    }

    /// TD-0021 P4 (D1): have we already settled a call with this `(vkey, idem_key)` inside
    /// the window? Returns the original settlement so the caller can reuse it. A row past its
    /// window is pruned on sight and reports unseen (a retry an hour later is a new logical
    /// call — D2's boundary is the feature, not a leak).
    pub fn seen_durable(
        &self,
        vkey: &str,
        idem_key: &str,
        now: OffsetDateTime,
    ) -> Result<Option<(u64, u64)>, LedgerStoreError> {
        self.block(self.seen_async(vkey, idem_key, now))
    }

    async fn seen_async(
        &self,
        vkey: &str,
        idem_key: &str,
        now: OffsetDateTime,
    ) -> Result<Option<(u64, u64)>, LedgerStoreError> {
        let now_ts = now.unix_timestamp();
        let row = sqlx::query_as::<_, (i64, i64, i64)>(
            "SELECT reservation, actual, expires_at FROM idempotency_dedup \
             WHERE vkey = $1 AND idem_key = $2",
        )
        .bind(vkey)
        .bind(idem_key)
        .fetch_optional(&self.pool)
        .await?;
        match row {
            Some((reservation, actual, expires_at)) => {
                if expires_at <= now_ts {
                    // Past the window: prune and report unseen (count the call, D3).
                    sqlx::query("DELETE FROM idempotency_dedup WHERE vkey = $1 AND idem_key = $2")
                        .bind(vkey)
                        .bind(idem_key)
                        .execute(&self.pool)
                        .await?;
                    Ok(None)
                } else {
                    Ok(Some((reservation.max(0) as u64, actual.max(0) as u64)))
                }
            }
            None => Ok(None),
        }
    }

    /// Record the settlement of a logical call (TD-0021 P4 D1). The upsert keeps the freshest
    /// settlement for the key; the expiry mirrors the lease TTL so the record's lifetime
    /// matches the settlement it protects.
    pub fn record_durable(
        &self,
        vkey: &str,
        idem_key: &str,
        reservation: u64,
        actual: u64,
        now: OffsetDateTime,
        ttl: TimeDuration,
    ) -> Result<(), LedgerStoreError> {
        self.block(self.record_async(vkey, idem_key, reservation, actual, now, ttl))
    }

    async fn record_async(
        &self,
        vkey: &str,
        idem_key: &str,
        reservation: u64,
        actual: u64,
        now: OffsetDateTime,
        ttl: TimeDuration,
    ) -> Result<(), LedgerStoreError> {
        sqlx::query(
            "INSERT INTO idempotency_dedup (vkey, idem_key, reservation, actual, seen_at, expires_at) \
             VALUES ($1, $2, $3, $4, $5, $6) \
             ON CONFLICT (vkey, idem_key) DO UPDATE SET \
                 reservation = excluded.reservation, \
                 actual = excluded.actual, \
                 seen_at = excluded.seen_at, \
                 expires_at = excluded.expires_at",
        )
        .bind(vkey)
        .bind(idem_key)
        .bind(reservation as i64)
        .bind(actual as i64)
        .bind(now.unix_timestamp())
        .bind((now + ttl).unix_timestamp())
        .execute(&self.pool)
        .await?;
        Ok(())
    }

    /// Reclaim every unsettled lease expired at or before `now` (crash/leak backstop);
    /// returns how many were reclaimed — reservations AND pruned dedup rows, the same
    /// conflation the SQLite arm documents for the `leases_reclaimed` metric. Multi-scope by
    /// definition, so no scope lock: a conservative over-count is the safe direction.
    /// PR-B adds the NOT-EXISTS evidence guards alongside the tables they need.
    pub fn reclaim_expired_durable(&self, now: OffsetDateTime) -> Result<usize, LedgerStoreError> {
        self.block(self.reclaim_async(now))
    }

    async fn reclaim_async(&self, now: OffsetDateTime) -> Result<usize, LedgerStoreError> {
        let now_ts = now.unix_timestamp();
        let leases =
            sqlx::query("DELETE FROM budget_reservation WHERE settled = 0 AND expires_at <= $1")
                .bind(now_ts)
                .execute(&self.pool)
                .await?;
        // TD-0021 P4 review finding: the dedup table is not prune-on-sight only — without
        // this, a key used once and never retried lives forever.
        let dedup = sqlx::query("DELETE FROM idempotency_dedup WHERE expires_at <= $1")
            .bind(now_ts)
            .execute(&self.pool)
            .await?;
        Ok(usize::try_from(leases.rows_affected() + dedup.rows_affected()).unwrap_or(usize::MAX))
    }

    pub fn limit_durable(&self, scope: &str) -> Result<Option<u64>, LedgerStoreError> {
        self.block(self.limit_async(scope))
    }

    async fn limit_async(&self, scope: &str) -> Result<Option<u64>, LedgerStoreError> {
        let limit: Option<i64> =
            sqlx::query_scalar("SELECT MIN(limit_tokens) FROM budget_limit WHERE scope = $1")
                .bind(scope)
                .fetch_one(&self.pool)
                .await?;
        Ok(limit.map(|v| v.max(0) as u64))
    }

    /// Settled spend in one configured trailing window. Uses the store as the clock authority.
    pub fn spent_for_window_durable(
        &self,
        scope: &str,
        window: Window,
    ) -> Result<u64, LedgerStoreError> {
        self.block(self.spent_for_window_async(scope, window))
    }

    async fn spent_for_window_async(
        &self,
        scope: &str,
        window: Window,
    ) -> Result<u64, LedgerStoreError> {
        let start = window_start_ts(OffsetDateTime::now_utc(), window);
        let spent: i64 = sqlx::query_scalar(
            "SELECT COALESCE(SUM(actual), 0)::bigint FROM budget_reservation \
             WHERE scope = $1 AND settled = 1 AND COALESCE(settled_at, 0) > $2",
        )
        .bind(scope)
        .bind(start)
        .fetch_one(&self.pool)
        .await?;
        Ok(spent.max(0) as u64)
    }

    /// Compatibility view: settled spend in the scope's shortest configured trailing window.
    pub fn spent_durable(&self, scope: &str) -> Result<u64, LedgerStoreError> {
        self.spent_for_window_durable(scope, self.window_of_durable(scope)?)
    }

    /// Held (unsettled) ceilings. May transiently include not-yet-reclaimed expired leases —
    /// a conservative over-count for a read snapshot; `reserve` reclaims them before admitting.
    pub fn reserved_durable(&self, scope: &str) -> Result<u64, LedgerStoreError> {
        self.block(self.reserved_async(scope))
    }

    async fn reserved_async(&self, scope: &str) -> Result<u64, LedgerStoreError> {
        let reserved: i64 = sqlx::query_scalar(
            "SELECT COALESCE(SUM(ceiling), 0)::bigint FROM budget_reservation \
             WHERE scope = $1 AND settled = 0",
        )
        .bind(scope)
        .fetch_one(&self.pool)
        .await?;
        Ok(reserved.max(0) as u64)
    }

    /// Every configured budget (cap + window + policy), for rehydrating the operator's
    /// in-memory budget metadata on startup (ADR-0005 D3).
    pub fn list_budgets_durable(&self) -> Result<Vec<BudgetRow>, LedgerStoreError> {
        self.block(self.list_budgets_async())
    }

    async fn list_budgets_async(&self) -> Result<Vec<BudgetRow>, LedgerStoreError> {
        let rows = sqlx::query_as::<_, (String, Option<i64>, String, String)>(&format!(
            "SELECT scope, limit_tokens, \"window\", policy FROM budget_limit \
             ORDER BY scope, {WINDOW_ORDER_SQL}",
        ))
        .fetch_all(&self.pool)
        .await?;
        Ok(rows
            .into_iter()
            .map(|(scope, limit, window, policy)| BudgetRow {
                scope,
                limit: limit.map(|v| v.max(0) as u64),
                window: Window::parse(&window),
                policy: Policy::parse(&policy),
            })
            .collect())
    }

    /// Migration-only (TD-0016 P1): insert a legacy budget row verbatim. Companion to
    /// [`Self::insert_migrated_reservation`].
    pub fn insert_migrated_limit(
        &self,
        scope: &str,
        limit_tokens: Option<i64>,
        window: &str,
        policy: &str,
    ) -> Result<(), LedgerStoreError> {
        self.block(self.insert_migrated_limit_async(scope, limit_tokens, window, policy))
    }

    async fn insert_migrated_limit_async(
        &self,
        scope: &str,
        limit_tokens: Option<i64>,
        window: &str,
        policy: &str,
    ) -> Result<(), LedgerStoreError> {
        // ON CONFLICT DO UPDATE — never INSERT OR REPLACE (its delete+insert collides with
        // child FK rows once the evidence tables exist in PR-B).
        sqlx::query(
            "INSERT INTO budget_limit (scope, \"window\", limit_tokens, policy) \
             VALUES ($1, $2, $3, $4) \
             ON CONFLICT (scope, \"window\") DO UPDATE SET \
                 limit_tokens = excluded.limit_tokens, \
                 policy = excluded.policy",
        )
        .bind(scope)
        .bind(window)
        .bind(limit_tokens)
        .bind(policy)
        .execute(&self.pool)
        .await?;
        Ok(())
    }

    /// Migration-only (TD-0016 P1): insert a legacy reservation row verbatim, preserving its
    /// id and settled state. Not used by the live reserve path. `ON CONFLICT (id) DO UPDATE`
    /// keeps re-runs idempotent without the FK hazard of INSERT OR REPLACE, and the identity
    /// sequence is re-`setval`'d past the highest id so fresh reserves can never collide with
    /// a migrated one (the SQLite AUTOINCREMENT equivalent is implicit; PG's is not).
    #[allow(clippy::too_many_arguments)]
    pub fn insert_migrated_reservation(
        &self,
        id: i64,
        scope: &str,
        ceiling: i64,
        actual: i64,
        settled: i64,
        expires_at: i64,
        settled_at: Option<i64>,
    ) -> Result<(), LedgerStoreError> {
        self.block(self.insert_migrated_reservation_async(
            id, scope, ceiling, actual, settled, expires_at, settled_at,
        ))
    }

    #[allow(clippy::too_many_arguments)]
    async fn insert_migrated_reservation_async(
        &self,
        id: i64,
        scope: &str,
        ceiling: i64,
        actual: i64,
        settled: i64,
        expires_at: i64,
        settled_at: Option<i64>,
    ) -> Result<(), LedgerStoreError> {
        let mut tx = self.pool.begin().await?;
        sqlx::query(
            "INSERT INTO budget_reservation \
                 (id, scope, ceiling, actual, settled, expires_at, settled_at) \
             VALUES ($1, $2, $3, $4, $5, $6, $7) \
             ON CONFLICT (id) DO UPDATE SET \
                 scope = excluded.scope, \
                 ceiling = excluded.ceiling, \
                 actual = excluded.actual, \
                 settled = excluded.settled, \
                 expires_at = excluded.expires_at, \
                 settled_at = excluded.settled_at",
        )
        .bind(id)
        .bind(scope)
        .bind(ceiling)
        .bind(actual)
        .bind(settled)
        .bind(expires_at)
        .bind(settled_at)
        .execute(&mut *tx)
        .await?;
        sqlx::query(
            "SELECT setval(pg_get_serial_sequence('budget_reservation', 'id'), \
                            GREATEST((SELECT COALESCE(MAX(id), 1) FROM budget_reservation), 1))",
        )
        .execute(&mut *tx)
        .await?;
        tx.commit().await?;
        Ok(())
    }
}

fn checked_i64(limit: Option<u64>) -> Result<Option<i64>, LedgerStoreError> {
    limit
        .map(i64::try_from)
        .transpose()
        .map_err(|e| LedgerStoreError::Backend(format!("budget value out of range: {e}")))
}

impl LedgerView for PostgresLedger {
    fn limit(&self, scope: &str) -> Option<u64> {
        self.limit_durable(scope).ok().flatten()
    }
    fn spent(&self, scope: &str) -> u64 {
        self.spent_durable(scope).unwrap_or(0)
    }
    fn reserved(&self, scope: &str) -> u64 {
        self.reserved_durable(scope).unwrap_or(0)
    }
}

impl EnforcementLedger for PostgresLedger {
    fn set_limit(&mut self, scope: &str, limit: Option<u64>) {
        let _ = self.set_limit_durable(scope, limit, Window::Total, Policy::Block);
    }

    fn reserve(
        &mut self,
        scope: &str,
        ceiling: u64,
        now: OffsetDateTime,
        ttl: TimeDuration,
    ) -> Result<Reservation, Denied> {
        // Fail-closed: a backend error denies the call (a hard cap must not admit on a blind
        // write). Per-tier fail-open/closed policy (ADR-0005 D6) belongs at the proxy swap.
        match self.reserve_durable(scope, ceiling, now, ttl) {
            Ok(ReserveOutcome::Admitted(reservation)) => Ok(reservation),
            Ok(ReserveOutcome::Denied(denied)) => Err(denied),
            Err(_) => Err(Denied {
                scope: scope.to_string(),
                limit: 0,
                spent: 0,
                reserved: 0,
                requested_ceiling: ceiling,
            }),
        }
    }

    fn settle(&mut self, reservation_id: u64, actual: u64) {
        let _ = self.settle_durable(reservation_id, actual);
    }

    fn reclaim_expired(&mut self, now: OffsetDateTime) -> usize {
        self.reclaim_expired_durable(now).unwrap_or(0)
    }
}

